using System.Net;
using System.Text;
using NightOwl.Core.Findings;
using NightOwl.Core.Reports;

namespace NightOwl.Core.Export;

/// <summary>A self-contained report: one HTML file, no scripts, no network, readable in a browser or printed to PDF.</summary>
public static class HtmlReport
{
    public static string Write(ScanReport report, string? label = null)
    {
        static string E(string? s) => WebUtility.HtmlEncode(s ?? "");
        var open = ReportStats.Open(report).ToList();
        var counts = ReportStats.BySeverity(open);
        var sb = new StringBuilder();
        sb.Append("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
        sb.Append($"<title>Night Owl report: {E(Path.GetFileName(report.Project))}</title><style>{Css}</style></head><body><main>");
        sb.Append($"<h1>{E(Path.GetFileName(report.Project))}</h1>");
        sb.Append($"<p class=\"meta\">{E(report.Project)}<br>Scanned {report.StartedAt.ToUniversalTime():yyyy-MM-dd HH:mm} UTC in {report.Seconds:0.0}s");
        if (!string.IsNullOrWhiteSpace(label)) { sb.Append($" &middot; <b>{E(label)}</b>"); }
        sb.Append($"<br>Engines: {E(string.Join(", ", report.Engines.Select(e => $"{e.Engine} {e.Version}")))}</p>");

        sb.Append("<div class=\"kpis\">");
        foreach (var s in new[] { Severity.Critical, Severity.High, Severity.Medium, Severity.Low })
        {
            sb.Append($"<div class=\"kpi {s}\"><span>{s}</span><b>{ReportStats.Count(counts, s)}</b></div>");
        }

        sb.Append($"<div class=\"kpi\"><span>Open</span><b>{open.Count}</b></div></div>");

        foreach (var failed in report.Engines.Where(e => !e.Succeeded))
        {
            sb.Append($"<p class=\"warn\">{E(failed.Engine)} did not finish: {E(failed.Error)}. Results below may be incomplete.</p>");
        }

        if (report.Metrics is { Count: > 0 } metrics)
        {
            sb.Append("<h2>Code quality</h2><ul class=\"metrics\">");
            foreach (var (key, value) in metrics.OrderBy(m => m.Key, StringComparer.Ordinal))
            {
                sb.Append($"<li>{E(Quality.MetricNames.Label(key))}: <b>{E(Quality.MetricNames.Format(key, value))}</b></li>");
            }

            sb.Append("</ul>");
        }

        foreach (var group in open.GroupBy(f => f.Category).OrderBy(g => g.Key))
        {
            sb.Append($"<h2>{group.Key} ({group.Count()})</h2><table><thead><tr><th>Severity</th><th>Finding</th><th>Where</th><th>Fix</th></tr></thead><tbody>");
            foreach (var f in group.OrderByDescending(f => f.Severity).ThenBy(f => f.Title, StringComparer.Ordinal))
            {
                var where = f.Location?.Path is { } p ? $"{p}{(f.Location.StartLine is { } l ? ":" + l : "")}" : f.Package is { } pk ? $"{pk.Name}@{pk.Version}" : "";
                sb.Append($"<tr><td class=\"{f.Severity}\">{f.Severity.ToString().ToUpperInvariant()}</td><td>{E(f.Title)}<br><small>{E(f.RuleId)}");
                if (f.Triage != TriageState.New) { sb.Append($" &middot; {f.Triage}"); }
                if (f.Context != FindingContext.Production) { sb.Append($" &middot; {f.Context.ToString().ToLowerInvariant()}"); }
                sb.Append($"</small></td><td><code>{E(where)}</code></td><td>{E(string.Join(" / ", f.FixedVersions))}</td></tr>");
            }

            sb.Append("</tbody></table>");
        }

        if (open.Count == 0) { sb.Append("<p class=\"ok\">No open findings.</p>"); }
        sb.Append("<footer>Generated by Night Owl.</footer></main></body></html>");
        return sb.ToString();
    }

    private const string Css =
        "body{font:15px/1.5 system-ui,-apple-system,Segoe UI,sans-serif;color:#1d1d1f;margin:0;background:#fff}main{max-width:1000px;margin:0 auto;padding:32px 20px}" +
        "h1{margin:0 0 4px}h2{margin:28px 0 8px;font-size:1.1rem}.meta{color:#6b6b73;font-size:.85rem}.kpis{display:flex;gap:12px;flex-wrap:wrap;margin:18px 0}" +
        ".kpi{border:1px solid #e3e3e8;border-radius:8px;padding:8px 14px;min-width:90px}.kpi span{display:block;font-size:.7rem;text-transform:uppercase;color:#6b6b73}.kpi b{font-size:1.6rem}" +
        "table{width:100%;border-collapse:collapse;font-size:.85rem}th,td{text-align:left;padding:6px 8px;border-bottom:1px solid #e3e3e8;vertical-align:top}th{font-size:.7rem;text-transform:uppercase;color:#6b6b73}" +
        ".Critical{color:#b42318;font-weight:700}.High{color:#d9480f;font-weight:700}.Medium{color:#8a6a00;font-weight:700}.Low{color:#2f6fbf;font-weight:700}small{color:#6b6b73}" +
        ".warn{background:#fff4e5;border:1px solid #f0c36d;padding:8px 12px;border-radius:6px}.ok{color:#1a7f37}.metrics{padding-left:18px}footer{margin-top:32px;color:#6b6b73;font-size:.8rem}" +
        "code{font-size:.8rem;overflow-wrap:anywhere}@media print{tr{break-inside:avoid}}";
}
